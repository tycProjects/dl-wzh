package com.example.data.ai

import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.generationConfig
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.TimeoutCancellationException
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withTimeout

private const val TAG = "BioscienceAiService"

class BioscienceAiService {

    // Lazy initialization of the generative model to avoid startup crashes
    private val model by lazy {
        Firebase.ai.generativeModel(
            modelName = "gemini-3.8-flash",
            generationConfig = generationConfig {
                temperature = 0.7f
                topP = 0.95f
            }
        )
    }

    /**
     * Streams bioscience analysis response token by token to minimize latency.
     */
    fun streamScientificInquiry(prompt: String): Flow<String> = flow {
        val enhancedPrompt = """
            You are the Liquid Glass Bioscience Research Engine.
            The user is exploring cellular biology, osmosis, genetics, or biophysical fluids.
            Provide an authoritative, clear, and engaging scientific breakdown with:
            1. Core Biological Mechanism (biochemical pathways, molecular physics, thermodynamics)
            2. Cellular & Physiological Impact (e.g. membrane permeability, ion gradients, ATP yields)
            3. Liquid Glass Biophysics Analogy (how fluidity, viscosity, and surface tension apply)
            4. Practical Key Takeaways

            Topic / Query:
            $prompt
        """.trimIndent()

        try {
            var emittedAny = false
            withTimeout(60_000L) {
                model.generateContentStream(enhancedPrompt).collect { chunk ->
                    val chunkText = chunk.text.orEmpty()
                    if (chunkText.isNotEmpty()) {
                        emittedAny = true
                        emit(chunkText)
                    }
                }
            }
            if (!emittedAny) {
                emit("No response generated by the bioscience model.")
            }
        } catch (e: TimeoutCancellationException) {
            Log.e(TAG, "Streaming query timed out", e)
            emit("\n[Scientific calculation timed out after 60s. Please retry.]")
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Bioscience AI query failed", e)
            emit("\n[Error: ${e.localizedMessage ?: "Unknown scientific inference error"}]")
        }
    }
}
