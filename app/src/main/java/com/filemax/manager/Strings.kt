private val AR = "\\u0600-\\u06FF"
private val rx = Regex("(?<![$AR])(" + EN.keys.sortedByDescending { it.length }.joinToString("|") { Regex.escape(it) } + ")(?![$AR])")

fun tr(s: String): String = if (!Lang.english || s.none { it in '\u0600'..'\u06FF' }) s else rx.replace(s) { EN[it.value] ?: it.value }

/** Same-package override of material3 Text: translates Arabic source strings when English is selected. */
@Composable
fun Text(text: String, modifier: Modifier = Modifier, color: Color = Color.Unspecified, fontSize: TextUnit = TextUnit.Unspecified,
         fontWeight: FontWeight? = null, fontFamily: FontFamily? = null, textAlign: TextAlign? = null,
         overflow: TextOverflow = TextOverflow.Clip, maxLines: Int = Int.MAX_VALUE, style: TextStyle = LocalTextStyle.current) {
    androidx.compose.material3.Text(text = tr(text), modifier = modifier, color = color, fontSize = fontSize, fontWeight = fontWeight,
        fontFamily = fontFamily, textAlign = textAlign, overflow = overflow, maxLines = maxLines, style = style)
}
